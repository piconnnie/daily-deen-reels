import React from 'react';
import * as Remotion from 'remotion';
import {AbsoluteFill, interpolate, staticFile, useCurrentFrame} from 'remotion';
import {alpha, fonts, safe, safeBox} from '../brand/tokens';
import {useColors} from '../brand/theme';

// Remotion renamed the HTML5 <Audio> component to <Html5Audio>; support both so
// the project works across 4.x releases. Volume is a plain number (the bed is
// already faded in/out by scripts/synth-audio.py).
const HtmlAudio = ((Remotion as unknown as Record<string, unknown>).Html5Audio ??
  (Remotion as unknown as Record<string, unknown>).Audio) as React.FC<{src: string; volume?: number}>;

// Pre-mixed music bed + SFX, synthesized locally by scripts/synth-audio.py from
// the scene sfx cues. One file keeps sync deterministic.
export const SoundDesignTrack: React.FC<{src: string | null; volume: number}> = ({src, volume}) => {
  if (!src) return null;
  return <HtmlAudio src={staticFile(src)} volume={volume} />;
};

// Narration file (optional). Generated by a configured TTS provider or recorded.
export const VoiceoverTrack: React.FC<{src: string | null; volume: number}> = ({src, volume}) => {
  if (!src) return null;
  return <HtmlAudio src={staticFile(src)} volume={volume} />;
};

export interface SubtitleCue {
  from: number;
  to: number;
  text: string;
}

// Burned-in subtitles for narrated reels. Sits in the lower safe band, above
// Instagram's caption chrome. Not rendered when voiceover is off, because the
// on-screen copy already carries the message.
export const SubtitleTrack: React.FC<{cues: SubtitleCue[]}> = ({cues}) => {
  const frame = useCurrentFrame();
  const colors = useColors();
  const cue = cues.find((c) => frame >= c.from && frame < c.to);
  if (!cue) return null;
  const local = frame - cue.from;
  const opacity = interpolate(local, [0, 4], [0, 1], {extrapolateRight: 'clamp'});
  return (
    <AbsoluteFill style={{pointerEvents: 'none'}}>
      <div
        style={{
          position: 'absolute',
          left: safeBox.x,
          width: safeBox.width,
          bottom: safe.bottom + 20,
          display: 'flex',
          justifyContent: 'center',
          opacity,
        }}
      >
        <span
          style={{
            fontFamily: fonts.body,
            fontWeight: 600,
            fontSize: 40,
            lineHeight: 1.25,
            color: colors.offWhite,
            background: alpha(colors.navy, 0.82),
            padding: '10px 20px',
            borderRadius: 12,
            textAlign: 'center',
          }}
        >
          {cue.text}
        </span>
      </div>
    </AbsoluteFill>
  );
};
